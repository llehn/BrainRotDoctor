    private static void MergeRedesign(Dictionary<string, Dictionary<string, string>> tables)
    {
        foreach ((string code, Dictionary<string, string> extra) in RedesignTables())
        {
            if (!tables.TryGetValue(code, out Dictionary<string, string>? table))
            {
                continue;
            }

            foreach ((string key, string value) in extra)
            {
                table[key] = value;
            }
        }
    }

